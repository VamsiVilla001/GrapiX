// Colour transfer curves in the browser layer, matching the engine
// (build plan 11.4, ADR-0002 B.1).
//
// **The browser and the engine must use the same curve to the last bit.** A
// preview composited in display-encoded values and an engine composited in
// linear produce images that look alike until a ramp or a cross-fade puts them
// side by side, and then the pixel gate fails for a reason nobody can find.
// B.1's answer is one implementation; a browser cannot call Rust, so the
// curve is written here in TypeScript — and that creates exactly the two
// implementations invariant 27 says will drift.
//
// The drift is pinned by `transfer-reference.ts`: the reference values were
// generated by the Rust functions themselves, and `color-transfer.test.ts`
// asserts these functions match them. A curve changed on one side without the
// other fails that test instead of a pixel gate nobody traces back.

/// sRGB's opto-electronic transfer function: linear → display-encoded.
///
/// The piecewise curve from IEC 61966-2-1, not the 2.2 power law it is often
/// described as — the difference is largest in the shadows, which is precisely
/// where a broadcast graphic's anti-aliased edges live. Mirrors
/// `srgb_encode` in `Shared/contracts/src/color.rs`.
export function srgbEncode(linear: number): number {
  return linear <= 0.003_130_8
    ? 12.92 * linear
    : 1.055 * Math.pow(linear, 1.0 / 2.4) - 0.055;
}

/// sRGB's electro-optical transfer function: display-encoded → linear.
export function srgbDecode(encoded: number): number {
  return encoded <= 0.040_449_936_474_468_28
    ? encoded / 12.92
    : Math.pow((encoded + 0.055) / 1.055, 2.4);
}

/// ITU-R BT.709's OETF: scene-linear → signal.
///
/// This is the *signal* encoding. BT.1886 — the display EOTF a broadcast
/// monitor applies — is a 2.4 power law and is deliberately **not** the
/// inverse of this curve: the difference is the end-to-end system gamma (about
/// 1.2) that broadcast viewing assumes. Mirrors `rec709_encode`.
export function rec709Encode(linear: number): number {
  return linear < 0.018 ? 4.5 * linear : 1.099 * Math.pow(linear, 0.45) - 0.099;
}

/// The inverse of `rec709Encode`: signal → scene-linear.
export function rec709Decode(encoded: number): number {
  return encoded < 0.081
    ? encoded / 4.5
    : Math.pow((encoded + 0.099) / 1.099, 1.0 / 0.45);
}
