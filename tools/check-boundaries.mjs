#!/usr/bin/env node
// Structural guard. Cheap, so run it after touching any manifest or moving any
// file. It fails on a cross-domain dependency rather than letting one appear
// quietly and be discovered months later.
//
// Enforces:
//   invariant 1  Shared is contracts, and cannot depend on Editor or Playout
//   invariant 3  Editor and Playout never import renderer internals
//   invariant 23 generated-ts is generated, never hand-authored

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const violations = [];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (["node_modules", "target", "dist", ".git", ".claude", "bindings"].includes(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const files = walk(ROOT);
const rel = (f) => relative(ROOT, f).split(sep).join("/");

// ---------------------------------------------------------------------------
// invariant 1: the Shared dependency arrow points only inward.
// ---------------------------------------------------------------------------
const PRODUCT_CRATES = ["gx-engine-host", "gx-render-worker"];
for (const file of files.filter((f) => rel(f).startsWith("Shared/") && f.endsWith("Cargo.toml"))) {
  const text = readFileSync(file, "utf8");
  for (const crate of PRODUCT_CRATES) {
    if (new RegExp(`^\\s*${crate}\\s*=`, "m").test(text)) {
      violations.push(`${rel(file)}: Shared depends on product crate ${crate} (invariant 1)`);
    }
  }
}
for (const file of files.filter((f) => rel(f).startsWith("Shared/") && /\.(ts|tsx|rs)$/.test(f))) {
  const text = readFileSync(file, "utf8");
  if (/from\s+["'][^"']*(Editor|Playout)\//.test(text) || /\buse\s+(gx_engine_host|gx_render_worker)\b/.test(text)) {
    violations.push(`${rel(file)}: Shared imports from a product (invariant 1)`);
  }
}

// ---------------------------------------------------------------------------
// invariant 3: products never reach into renderer internals, and the two
// products never import each other.
// ---------------------------------------------------------------------------
for (const file of files.filter((f) => /^(Editor|Playout)\//.test(rel(f)) && /\.(ts|tsx)$/.test(f))) {
  const text = readFileSync(file, "utf8");
  const domain = rel(file).split("/")[0];
  const other = domain === "Editor" ? "Playout" : "Editor";
  if (new RegExp(`from\\s+["'][^"']*${other}/`).test(text)) {
    violations.push(`${rel(file)}: ${domain} imports ${other} (invariant 1)`);
  }
  if (/from\s+["'][^"']*render-engine\//.test(text) || /from\s+["'][^"']*gx-render-worker/.test(text)) {
    violations.push(`${rel(file)}: ${domain} imports renderer internals (invariant 3)`);
  }
}

// ---------------------------------------------------------------------------
// invariant 23: every file in generated-ts/src carries a generated header.
// A hand-written file there is drift wearing a generated label.
// ---------------------------------------------------------------------------
const GEN_DIR = "Shared/generated-ts/src";
for (const file of files.filter((f) => rel(f).startsWith(GEN_DIR) && f.endsWith(".ts"))) {
  const head = readFileSync(file, "utf8").slice(0, 200);
  if (!/generated by|GENERATED by/i.test(head)) {
    violations.push(`${rel(file)}: hand-authored file in generated output (invariant 23)`);
  }
}

if (violations.length > 0) {
  console.error("check:boundaries FAILED\n");
  for (const v of violations) console.error(`  ${v}`);
  console.error(`\n${violations.length} violation(s). See docs/invariants.md.`);
  process.exit(1);
}
console.log("check:boundaries OK");
