#!/usr/bin/env node
// Transcribe EffectCraft's effect catalogue into the contract (build plan 11.69).
//
// Source: `docs/effects.md` of the pinned reference clone (`agent/reference/effectcraft`,
// MIT OR Apache-2.0), which EffectCraft generates from its own registry. Only the
// listing is taken (category, display name, id, parameter count, GPU flag): no code.
// The output is `Shared/contracts/src/effect_catalog_data.rs`; edit neither by hand.
//
//   node tools/gen-effect-catalog.mjs [path/to/effectcraft]

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const reference = process.argv[2] ?? join(ROOT, "..", "reference", "effectcraft");

/** Rows of the catalogue: `[category, name, id, params, gpu]`. Pure over the document text. */
export function parseCatalogue(markdown) {
  const rows = [];
  let category;
  for (const line of markdown.split(/\r?\n/)) {
    const heading = /^## (.+)$/.exec(line);
    if (heading) {
      category = heading[1].trim();
      continue;
    }
    const row = /^\| (.+?) \| `(ec\.[^`]+)` \| (\d+) \| (GPU)? ?\| (32)? ?\| .+? \|$/.exec(line);
    if (row && category) rows.push([category, row[1], row[2], Number(row[3]), row[4] === "GPU"]);
  }
  return rows;
}

const quote = (text) => JSON.stringify(text);

export function render(rows) {
  const lines = rows.map(
    ([category, name, id, params, gpu]) => `    (${quote(category)}, ${quote(name)}, ${quote(id)}, ${params}, ${gpu}),`,
  );
  return `// GENERATED by tools/gen-effect-catalog.mjs from EffectCraft's docs/effects.md. Do not edit.
//
// The listing (category, display name, id, parameter count, GPU flag) of EffectCraft's
// effect registry, Copyright the EffectCraft contributors, MIT OR Apache-2.0
// (ADR-0003; third-party notices). A listing only: no EffectCraft code is here.

/// \`(category, display name, EffectCraft id, parameter count, runs on EffectCraft's GPU)\`.
pub const EFFECTCRAFT_CATALOG: &[(&str, &str, &str, u16, bool)] = &[
${lines.join("\n")}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rows = parseCatalogue(readFileSync(join(reference, "docs", "effects.md"), "utf8"));
  if (rows.length === 0) throw new Error("no effects parsed: the catalogue's format changed");
  writeFileSync(join(ROOT, "Shared", "contracts", "src", "effect_catalog_data.rs"), render(rows));
  console.log(`wrote ${rows.length} effects`);
}
