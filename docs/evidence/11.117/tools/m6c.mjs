import { connect, LOG, at } from "./lib.mjs";
const c = await connect(9333, 110);
const { ev, click, mouse, wait, shot, geometry, key } = c;
const out = {};
const g = await geometry();
const shapes = () => ev(`return [...new Set([...document.querySelectorAll('button[data-action="select"][data-for]')].map((b) => b.dataset.for))].filter((x) => x.startsWith("shape"));`);
await ev(`document.getElementById("tool-pen").click(); const s = document.getElementById("pen-creates"); s.value = "shape"; s.dispatchEvent(new Event("change", { bubbles: true })); return 1;`);
const q = [at(g, 1300, 700), at(g, 1600, 700), at(g, 1600, 900), at(g, 1300, 900)];
for (const p of q) await click(p);
await mouse([{ type: "mouseMoved", ...q[0], wait: 150 }]);
await click(q[0]); await wait(1200);
out.shapes = await shapes();
await ev(`document.getElementById("tool-selection").click(); document.querySelector('button[data-action="select"][data-for="rect-1"]').click(); await new Promise(r=>setTimeout(r,700)); return 1;`);
out.options = await ev(`return [...document.querySelectorAll('#masks-mount select[aria-label="Shape to copy as a mask"] option')].map((o) => o.value);`);
await ev(`const b = [...document.querySelectorAll("#masks-mount button")].find((x) => x.textContent === "Copy as mask"); b.click(); await new Promise(r=>setTimeout(r,1000)); return 1;`);
out.afterCopy = { rows: await ev(`return document.querySelectorAll("#masks-mount .mask-row").length;`), overlay: await ev(`return document.querySelectorAll("#viewport-overlay .overlay-mask").length;`), log: await ev(`return ${LOG}.slice(0, 1);`) };
await ev(`const b = [...document.querySelectorAll("#masks-mount button")].find((x) => x.textContent === "To shape"); b.click(); await new Promise(r=>setTimeout(r,1000)); return 1;`);
out.afterToShape = { shapes: await shapes(), log: await ev(`return ${LOG}.slice(0, 1);`) };
await shot("m6-copy");
console.log(JSON.stringify(out, null, 1));
c.done();
